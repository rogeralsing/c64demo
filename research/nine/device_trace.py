ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/"build/research/nine"
OUT=BASE/"device-analysis"
PRG_SHA="a257fa0436bc0d97fbeaa906c55489786a26ee6a9213aa3fd0d8e21f9612d839"
GENERATED_SHA="507a2c6b869db6c55a7730eae18bd5f1688415a87b4071577c85ce0e21cb995b"
FAMILIES=(0x3000,0x3400,0x3800)
TRACE=re.compile(
    r"^#(?P<checkpoint>\d+) \(Trace store (?P<target>[0-9a-f]{4})\)\s+"
    r"(?P<line>\d+)/\$[0-9a-f]+,\s+(?P<cycle>\d+)/\$[0-9a-f]+\n"
    r"\.C:(?P<pc>[0-9a-f]+)\s+[^\n]*?"
    r"- A:(?P<a>[0-9a-f]+) X:(?P<x>[0-9a-f]+) Y:(?P<y>[0-9a-f]+) "
    r"SP:(?P<sp>[0-9a-f]+) [^\n]*?\s+(?P<clock>\d+)\n",re.M|re.I)


def sha(data):return hashlib.sha256(data).hexdigest()


def source_map(generated):
    return dict(program_sha256=PRG_SHA,generated_RAM_sha256=GENERATED_SHA,
                families=[dict(start=b,bytes=673,cells=21,cell_bytes=32,
                               sha256=sha(generated[b:b+673])) for b in FAMILIES],
                indirect_family_operand=[0x9BD6,0x9BD7],stop_row_pointer=[0x70,0x71],
                transient_patches=[dict(offset=0x18,normal_opcode=0x8E,patched_opcode=0x8F,
                                        meaning="STX D011 becomes SAX D011"),
                                   dict(offset=0x1B,normal_opcode=0xA9,patched_opcode=0x60,
                                        meaning="LDA immediate becomes early RTS")],
                pointer_table_switches=[dict(row=2,value=0x50),dict(row=17,value=0x60)],
                before_call=0x9BB1,after_call=0x9BB4,after_restoration=0x9BE4,
                expected_store_count="7*stop_row+6; stop row0 has only6 stores, no pattern/pointer switch",
                scope="Original generated bytes already independently proved. No CPU execution or native timing asserted by this map.")


def family_state(ram,generated,restored=False):
    assert ram[0x9BD5]==0x4C
    target=int.from_bytes(ram[0x9BD6:0x9BD8],"little")
    stop=int.from_bytes(ram[0x70:0x72],"little")
    assert target in FAMILIES and 0<=stop-target<=640 and (stop-target)%32==0
    row=(stop-target)//32
    baseline=ram[0x8DD4]
    fine=ram[0x62]&7
    assert baseline in (0x34,0x38) and target==(baseline-(4 if fine else 0))<<8
    expected=bytearray(generated)
    if not restored:expected[stop+0x18],expected[stop+0x1B]=0x8F,0x60
    for base in FAMILIES:
        assert ram[base:base+673]==expected[base:base+673],f"Generated family differs at{base:04X}"
    assert ram[0x9BCF:0x9BD3]==bytes.fromhex("a2 70 a4 67")
    return dict(target=target,stop_address=stop,stop_row=row,restored=restored,
                opcode_at_18=ram[stop+0x18],opcode_at_1B=ram[stop+0x1B],
                colors_65_66_67=list(ram[0x65:0x68]),all2019_family_bytes_match=True)


def expected_stores(ram,state):
    """Read fixed cells as data; no CPU, flags, raster or DMA simulation.

    BCS+0, BIT and NOP change no store value; LDA establishes the literal
    A source. X70 and Y67 are set by the verified original call prelude.
    """
    rows=[]
    a=None
    for row in range(state["stop_row"]+1):
        start=state["target"]+32*row
        pc=start
        while pc<start+32:
            op=ram[pc]
            if op==0x60:
                assert row==state["stop_row"] and pc==start+0x1B
                break
            if op==0xA5:a=ram[ram[pc+1]];pc+=2;continue
            if op==0xA9:a=ram[pc+1];pc+=2;continue
            if op in (0x8D,0x9D,0x8C,0x8E,0x8F):
                address=int.from_bytes(ram[pc+1:pc+3],"little")+(0x70 if op==0x9D else 0)
                value={0x8D:a,0x9D:a,0x8C:ram[0x67],0x8E:0x70,0x8F:(a&0x70)}[op]
                assert address in (0xD011,0xD021,0xD018,0x7FFF)
                rows.append(dict(row=row,pc=pc,opcode=op,address=address,value=value))
                pc+=3;continue
            if op in (0xB0,0x24):pc+=2;continue
            if op==0x2C:pc+=3;continue
            assert op==0xEA,hex(op)
            pc+=1
    assert len(rows)==7*state["stop_row"]+6
    return rows


def parse_traces(text,ram,first_clock,last_clock):
    result=[]
    for match in TRACE.finditer(text):
        f=match.groupdict()
        item={k:int(v,16 if k in ("target","pc","a","x","y","sp") else 10) for k,v in f.items()}
        if not first_clock<=item["clock"]<=last_clock:continue
        pc=item["pc"]
        op=ram[pc]
        assert op in (0x8D,0x9D,0x8C,0x8E,0x8F)
        address=int.from_bytes(ram[pc+1:pc+3],"little")+(item["x"] if op==0x9D else 0)
        assert address==item["target"]
        value={0x8D:item["a"],0x9D:item["a"],0x8C:item["y"],0x8E:item["x"],0x8F:item["a"]&item["x"]}[op]
        item.update(address=address,value=value,opcode=op)
        result.append(item)
    return result


def capture(directory,stem,pc,events):
    raw=directory/f"ram-{stem}.bin"
    path=directory/f"{stem}.vsf"
    event=events[path.name]
    data=physical_ram(path)
    if raw.exists():
        raw_event=events[raw.name]
        assert raw_event["bank"]=="ram" and raw_event["first"]==0 and raw_event["end_inclusive"]==65535
        assert raw_event["registers"]==event["registers"]
        assert len(data)==65536 and raw.read_bytes()==data
    reg=event["registers"]
    assert reg["pc"]==pc and events[path.name]["registers"]==reg
    state=read_snapshot(path)
    assert (state["vicii"]["raster_line"],state["vicii"]["raster_cycle"])==(reg["raster_line"],reg["raster_cycle"])
    assert state["modules"]["MAINCPU"]["version"]==[1,4]
    clock=int.from_bytes(module_payload(path,"MAINCPU")[:8],"little")
    assert clock==reg["clock"]
    return data,state,reg,dict(stem=stem,pc=pc,registers=reg,raw_file=str(raw) if raw.exists() else None,
                               physical_RAM_sha256=sha(data),snapshot_sha256=sha(path.read_bytes()),
                               all65536_RAM_bytes_match_raw_dump=True if raw.exists() else None)


def schemas(output):
    archive=ROOT/"build/research/quondam/hardware-source/vice-3.10.tar.gz"
    assert sha(archive.read_bytes())==SOURCE_ARCHIVE_SHA256
    members=[]
    with tarfile.open(archive,"r:gz") as source:
        for path,lines in (("src/core/viacore.c",[1952,1979]),
                           ("src/drive/drive-snapshot.c",[149,184]),
                           ("src/drive/drivecpu.c",[543,572])):
            member=f"vice-3.10/{path}"
            data=source.extractfile(member).read()
            target=output/"hardware-source"/member
            target.parent.mkdir(parents=True,exist_ok=True)
            target.write_bytes(data)
            members.append(dict(member=member,file=str(target),sha256=sha(data),writer_lines=lines))
    return dict(archive_sha256=SOURCE_ARCHIVE_SHA256,members=members,
                CLOCK_bytes=8,exclusions=[],
                VIA_roundtrip_note="Writer packs combinedCB1 inbit20 (1976-1977); reader testsCB1in10/out08 (2152-2153). Values retained; no claim this alone explains every control difference.")


def map_differences(comparison,a,b):
    """Name the source fields that actually differ; never remove any bytes."""
    cpu_fields=((0,8,"drive_clock"),(8,1,"A"),(9,1,"X"),(10,1,"Y"),(11,1,"SP"),
                (12,2,"PC"),(14,1,"status"),(15,4,"last_opcode_info"),(19,8,"last_clk"),
                (27,8,"cycle_accum"),(35,8,"last_exc_cycles"),(43,8,"stop_clk"),(51,1,"cpu_last_data"))
    mapped=True
    for item in comparison["different_modules"]:
        name=item["module"]
        if name in ("1541VIA1D0","VIA2D0") and item["first_version"]==item["second_version"]==[2,2]:
            fields=((6,2,"VIA_T1_counter"),(12,2,"VIA_T2_counter"),(22,1,"packed_CA2_CB2_CB1_levels"))
            source="src/core/viacore.c:1958,1963,1973-1977"
        elif name=="DRIVE8" and item["first_version"]==item["second_version"]==[2,0]:
            fields=((27,4,"GCR_head_offset"),)
            source="src/drive/drive-snapshot.c:149-184"
        elif name=="DRIVECPU0" and item["first_version"]==item["second_version"]==[1,3]:
            fields=cpu_fields
            source="src/drive/drivecpu.c:560-572"
        else:
            fields=()
            source="Unmapped; requires review"
        aa,bb=module_payload(a,name),module_payload(b,name)
        covered=set()
        decoded=[]
        for offset,size,label in fields:
            if any(offset<=d["payload_offset"]<offset+size for d in item["differences"]):
                decoded.append(dict(field=label,payload_offset=offset,bytes=size,
                                    traced=int.from_bytes(aa[offset:offset+size],"little"),
                                    control=int.from_bytes(bb[offset:offset+size],"little")))
                covered.update(range(offset,offset+size))
        item.update(source=source,decoded_differing_fields=decoded)
        mapped &= (len(aa)==len(bb) and all(d["payload_offset"] in covered for d in item["differences"]))
    comparison.update(whole_files_equal=a.read_bytes()==b.read_bytes(),CPU_RAM_VIC_exact=True,
                      all_differing_fields_source_mapped=bool(mapped),whole_machine_equality_claimed=a.read_bytes()==b.read_bytes(),
                      interpretation="All bytes retained. Equality applies to capturedC64CPU/RAM/VIC; drive execution/scheduling/line-state differences prohibit whole-machine equality. Exact cause is not isolated.")
    return bool(mapped)


def analyze(directory,generated,stems,output):
    text=(directory/"monitor.log").read_text(errors="replace")
    events={event["filename"]:event for event in contexts(text)}
    captured=[capture(directory,stem,pc,events) for stem,pc in zip(stems,(0x9BB1,0x9BB4,0x9BB4,0x9BE4))]
    before,after,control,restored=[r[0] for r in captured]
    before_state,after_state,control_state,restored_state=[r[1] for r in captured]
    pre,post,ctrl,done=[r[2] for r in captured]
    family=family_state(before,generated)
    assert family["stop_row"]==20,"Canonical full trace must reach row20; preserve clipped calls separately"
    assert before[0x9BB1:0x9BB4]==bytes.fromhex("20 bc 9b")
    assert pre["flags"]&4 and post["flags"]&4
    expected=expected_stores(before,family)
    trace=parse_traces(text,before,pre["clock"],post["clock"])
    assert len(trace)==len(expected),(len(trace),len(expected))
    for actual,exp in zip(trace,expected):
        assert all(actual[k]==exp[k] for k in ("pc","address","value","opcode")),(actual,exp)
        assert actual["x"]==0x70 and actual["y"]==before[0x67]
        assert actual["sp"]==(pre["sp"]-2)&255
        actual["row"]=exp["row"]
    assert post["sp"]==pre["sp"] and (post["a"],post["x"],post["y"])==(before[0x66],0x70,before[0x67])
    expected_RAM=bytearray(before)
    expected_RAM[0x100+pre["sp"]]=0x9B
    expected_RAM[0x100+((pre["sp"]-1)&255)]=0xB3
    for store in expected:
        if store["address"]==0x7FFF:expected_RAM[0x7FFF]=store["value"]
    assert expected_RAM==after,"JSR/cell-return physical RAM differs from original store/stack contract"
    assert family_state(after,generated)==family
    assert after==control and post==ctrl
    a,b=(directory/f"{stem}.vsf" for stem in stems[1:3])
    comparison=compare_modules(a,b)
    for name in ("MAINCPU","C64MEM","VIC-II"):
        assert module_payload(a,name)==module_payload(b,name),name
    source_schemas=schemas(output)
    fields_mapped=map_differences(comparison,a,b)
    expected_restored=bytearray(control)
    stop=family["stop_address"]
    expected_restored[stop+0x18],expected_restored[stop+0x1B]=0x8E,0xA9
    assert expected_restored==restored
    assert done["sp"]==ctrl["sp"]
    restored_family=family_state(restored,generated,restored=True)
    assert restored_state["vicii"]["regs"][0x11]==0x18
    starts=[next(r for r in trace if r["row"]==row) for row in range(21)]
    periods=[b["clock"]-a["clock"] for a,b in zip(starts,starts[1:])]
    switches=[r for r in trace if r["address"]==0xD018]
    assert [(r["row"],r["value"]) for r in switches]==[(2,0x50),(17,0x60)]
    cia2=before_state["cia"]["CIA2"]
    assert cia2["pra"]&3==0
    bank=(cia2["ddra"]&3)*0x4000
    assert bank==0x4000
    for item in switches:
        item["screen_address"]=bank+((item["value"]>>4)<<10)
        item["sprite_pointer_table"]=item["screen_address"]+0x3F8
        item["prepared_table_bytes"]=list(before[item["sprite_pointer_table"]:item["sprite_pointer_table"]+8])
    end=events[f"{stems[-1]}.vsf"]["transcript_line"]
    prefix="\n".join(text.splitlines()[:end])+"\n"
    transcript_path=output/"device-transcript.log"
    transcript_path.write_text(prefix)
    initial_prefix="\n".join(text.splitlines()[:events[f"{stems[0]}.vsf"]["transcript_line"]])
    parents=[dict(file=p,sha256=sha(Path(p).read_bytes()))
             for p in re.findall(r'^undump "([^"]+)"',initial_prefix,re.M)]
    result=dict(pass_=fields_mapped,program_sha256=PRG_SHA,script_sha256=sha(Path(__file__).read_bytes()),
                generated_RAM_sha256=GENERATED_SHA,inputs=[r[3] for r in captured],family=family,
                trace=trace,trace_count=len(trace),store_counts={f"{k:04X}":v for k,v in Counter(r["address"] for r in trace).items()},
                all_expected_PC_values_and_targets_match=True,all65536_call_RAM_bytes_match=True,
                post_call_transient_patches_unchanged=True,restored_family=restored_family,
                all65536_restoration_RAM_bytes_match=True,control_comparison=comparison,
                control_field_schemas=source_schemas,
                observed_call_cycles=post["clock"]-pre["clock"],
                observed_restore_cycles=done["clock"]-ctrl["clock"],
                row_start_trace_cycle_offsets=[r["cycle"] for r in starts],row_start_trace_rasters=[r["line"] for r in starts],
                consecutive_row_start_clock_deltas=periods,pointer_table_switches=switches,
                literal_shadows_65_66_67=list(before[0x65:0x68]),CIA2_latch=cia2["pra"],CIA2_direction=cia2["ddra"],
                inferred_VIC_bank=bank,
                selector_baseline_page=before[0x8DD4],fine_scroll_62=before[0x62]&7,
                initial_snapshot_parents=parents,
                transcript=dict(file=str(transcript_path),sha256=sha(prefix.encode()),original_prefix_end_line=end),
                scope="One original native family/stoprow/control run. Monitor trace timestamps are observed checkpoint clocks, not a calibrated physical bus-phase, FPS or other-VIC-revision claim.")
    result["pass"]=result.pop("pass_")
    (output/"device-proof.json").write_text(json.dumps(result,indent=2)+"\n")
    assert fields_mapped,"Unmapped all-module control differences; retain receipt and inspect without masking"
    print(f"PASS:{len(trace)}stores, family{family['target']:04X},stoprow20;allRAM/controlVIC/restorationexact.")


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--capture",type=Path,default=BASE/"native-01")
    parser.add_argument("--output",type=Path,default=OUT)
    parser.add_argument("--prepare",action="store_true",help="Write source map only, no native PASS result")
    args=parser.parse_args()
    assert sha((BASE/"lft-nine.prg").read_bytes())==PRG_SHA
    generated=(BASE/"binary/generated-ram.bin").read_bytes()
    assert len(generated)==65536 and sha(generated)==GENERATED_SHA
    args.output.mkdir(parents=True,exist_ok=True)
    mapping=source_map(generated)
    (args.output/"device-source-map.json").write_text(json.dumps(mapping,indent=2)+"\n")
    if args.prepare:
        print("Prepared Device source map; no native proof run.")
        return
    analyze(args.capture,generated,("device-full-before-cells","device-full-after-cells-traced",
                                    "device-full-after-cells-control","device-full-restored"),args.output)


if __name__=="__main__":main()
