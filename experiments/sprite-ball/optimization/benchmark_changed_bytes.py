#!/usr/bin/env python3
"""Measure assembled conditional sprite stores against verified native poses.

This benchmark protects exact sprite output and matching VIC-bank copies. The
credible regression is lost accumulator state or stale pixels when a store is
skipped. Existing scene verification owns polygon geometry; this benchmark owns
the alternative machine-code kernel and instruction timing, with no product seam.
"""

import argparse
import hashlib
import json
from pathlib import Path
import statistics
import subprocess

from py65.devices.mpu6502 import MPU


HERE = Path(__file__).resolve().parent
SOURCE = """// Standalone kernels retain the runtime's column-major markers and row-major output.
.const MARKERS=$1800
.const OUTPUT=$0c00
.const MIRROR=$7800
*=$8000
entry:
    .for (var sprite=0; sprite<8; sprite++) {
        .for (var column=0; column<3; column++) {
            lda #0
            .for (var row=0; row<19; row++) {
                eor MARKERS+sprite*64+column*21+row
CONDITIONAL
                sta OUTPUT+sprite*64+row*3+column
                sta MIRROR+sprite*64+row*3+column
LABEL
            }
        }
    }
    rts
end:
"""


def assemble(name, conditional):
    source = SOURCE.replace("CONDITIONAL", "                cmp OUTPUT+sprite*64+row*3+column\n                beq !same+" if conditional else "")
    source = source.replace("LABEL", "!same:" if conditional else "")
    source_path = HERE / f"{name}.asm"
    source_path.write_text(source)
    subprocess.run(["rtk", "proxy", "kickass", str(source_path), "-o", str(HERE / f"{name}.prg")], check=True, capture_output=True)
    data = (HERE / f"{name}.prg").read_bytes()
    return data[0] | data[1] << 8, data[2:]


def execute(kernel, markers, old):
    origin, code = kernel
    memory = [0] * 65536
    memory[origin:origin + len(code)] = code
    memory[0x1800:0x1a00] = markers
    for slot, data in enumerate(old):
        memory[0xc00 + slot * 64:0xc00 + slot * 64 + 63] = data
        memory[0x7800 + slot * 64:0x7800 + slot * 64 + 63] = data
    # The synthetic return address ends each actual RTS at an unexecuted sentinel.
    memory[0x1fe:0x200] = [0xff, 0x01]
    cpu = MPU(memory=memory, pc=origin)
    cpu.sp = 0xfd
    steps = 0
    while cpu.pc != 0x0200:
        cpu.step()
        steps += 1
        if steps > 10000:
            raise AssertionError("Machine-code kernel did not return")
    assert memory[origin:origin + len(code)] == list(code), "Kernel changed its own instructions"
    assert memory[0x1800:0x1a00] == markers, "Store kernel changed crossing markers"
    assert memory[0xc00:0xe00] == memory[0x7800:0x7a00], "VIC-bank copies differ"
    return cpu.processorCycles, bytes(memory[0xc00:0xe00])


def summarize(values):
    return {"minimum": min(values), "mean": statistics.mean(values), "maximum": max(values)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("trace", type=Path)
    args = parser.parse_args()
    raw = args.trace.read_bytes()
    trace = json.loads(raw)
    assert len(trace["frames"]) == 513, "Require the complete canonical native run"
    kernels = {name: assemble(name, conditional) for name, conditional in (("full-stores", False), ("conditional-stores", True))}
    results = []
    unchanged = changed = 0
    checked = 0
    for frame in trace["frames"]:
        assert len(frame["markers"]) == 512
        old = [slot["old"] for slot in frame["slots"]]
        assert len(old) == 8
        expected = bytearray(512)
        for slot in frame["slots"]:
            position = slot["slot"] * 64
            expected[position:position + 63] = bytes(slot["new"])
            for index in range(57):
                same = slot["old"][index] == slot["new"][index]
                unchanged += same
                changed += not same
        timings = {}
        for name, kernel in kernels.items():
            cycles, actual = execute(kernel, frame["markers"], old)
            assert actual == expected, (frame["index"], name, "sprite bytes differ from independent native-run oracle")
            timings[name] = cycles
            checked += 504
        results.append({"index": frame["index"], "bank": frame["bank"], "shape_mode": frame["shape_mode"], "render_cycles": frame["render_cycles"], **timings,
                        "cycle_difference": timings["conditional-stores"] - timings["full-stores"]})
    baseline = [r["full-stores"] for r in results]
    conditional = [r["conditional-stores"] for r in results]
    differences = [r["cycle_difference"] for r in results]
    report = {
        "strategy": "compare each generated byte with old target; store both VIC copies only when changed",
        "trace": str(args.trace.resolve()), "trace_sha256": hashlib.sha256(raw).hexdigest(),
        "measurement": "assembled 6502 machine code executed by py65 MPU; no VIC DMA or IRQ overhead included",
        "history": "old bytes supplied by actual destination buffer; two presentations old, including RUN-entry state",
        "presentations": len(results), "output_bytes_checked": checked,
        "sprite_mirror_bytes_checked": checked, "pixel_mismatches": 0,
        "baseline_cycles": summarize(baseline), "conditional_cycles": summarize(conditional), "difference_cycles": summarize(differences),
        "unchanged_bytes": unchanged, "changed_bytes": changed, "unchanged_fraction": unchanged / (unchanged + changed),
        "faster_presentations": sum(d < 0 for d in differences), "slower_presentations": sum(d > 0 for d in differences),
        "by_shape_mode": {
            str(mode): {"presentations": len(selected), "difference_cycles": summarize([r["cycle_difference"] for r in selected]),
                        "faster_presentations": sum(r["cycle_difference"] < 0 for r in selected)}
            for mode in sorted({r["shape_mode"] for r in results})
            for selected in [[r for r in results if r["shape_mode"] == mode]]
        },
        "kernel_code_bytes": {name: len(kernel[1]) for name, kernel in kernels.items()},
        "extra_code_bytes_per_fill_bank": len(kernels["conditional-stores"][1]) - len(kernels["full-stores"][1]),
        "extra_history_bytes": 0,
        "native_build": {"success": False, "error": "Fill A overlaps hardware vectors", "log": "native-build.log"},
        "formula_without_branch_page_penalty": "full=12; unchanged=11; changed=18 clocks per byte; break-even unchanged fraction > 6/7",
        "limitations": ["Kernel has contiguous standalone code; production segmented layout changes occasional taken-branch page penalties.",
                        "The prototype's native build must fit the original guarded memory map before promotion.",
                        "Full-render impact is kernel delta, not a separate native scene benchmark; changed duration can alter DMA/IRQ overlap."],
        "samples": results,
    }
    (HERE / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "samples"}, indent=2))


if __name__ == "__main__":
    main()
